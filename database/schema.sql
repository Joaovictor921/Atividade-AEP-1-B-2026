-- =====================================================================
-- Monitoramento da Infraestrutura Eletrica - Script de criacao (PostgreSQL / Supabase)
-- Reflete o DER da 1a entrega. Heranca modelada como "tabela por subclasse":
--   USUARIO <- OPERADOR | EQUIPAMENTO <- POSTE, TRANSFORMADOR
-- Execute no Supabase: SQL Editor > New query > cole este arquivo > Run.
-- (Nomes em snake_case, padrao do PostgreSQL.)
-- =====================================================================

-- ---------- USUARIO (superclasse) / OPERADOR (subclasse) ----------
CREATE TABLE IF NOT EXISTS usuario (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(120) NOT NULL,
    matricula VARCHAR(30)  NOT NULL UNIQUE,
    senha     VARCHAR(255) NOT NULL            -- hash PBKDF2 (nunca texto puro)
);

CREATE TABLE IF NOT EXISTS operador (
    usuario_id INTEGER PRIMARY KEY REFERENCES usuario(id) ON DELETE CASCADE,
    turno      VARCHAR(20) NOT NULL
);

-- ---------- EQUIPAMENTO (superclasse) / POSTE / TRANSFORMADOR ----------
CREATE TABLE IF NOT EXISTS equipamento (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    latitude  DOUBLE PRECISION NOT NULL CHECK (latitude  BETWEEN  -90 AND  90),
    longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    bairro    VARCHAR(100) NOT NULL,
    ativo     BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS poste (
    equipamento_id INTEGER PRIMARY KEY REFERENCES equipamento(id) ON DELETE CASCADE,
    tipo_poste     VARCHAR(60) NOT NULL,
    altura         DOUBLE PRECISION NOT NULL CHECK (altura > 0)
);

CREATE TABLE IF NOT EXISTS transformador (
    equipamento_id         INTEGER PRIMARY KEY REFERENCES equipamento(id) ON DELETE CASCADE,
    identificador_unico    VARCHAR(40) NOT NULL UNIQUE,
    capacidade_nominal     DOUBLE PRECISION NOT NULL CHECK (capacidade_nominal > 0),  -- kVA
    data_ultima_manutencao DATE
);

-- ---------- SENSOR / LEITURA_SENSOR (composicao 1:N) ----------
CREATE TABLE IF NOT EXISTS sensor (
    id                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identificador_dispositivo VARCHAR(60) NOT NULL UNIQUE,
    equipamento_id          INTEGER NOT NULL REFERENCES equipamento(id) ON DELETE CASCADE,
    data_instalacao         DATE,
    ativo                   BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS leitura_sensor (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id           INTEGER NOT NULL REFERENCES sensor(id) ON DELETE CASCADE,
    temperatura         DOUBLE PRECISION NOT NULL,   -- graus Celsius
    consumo_instantaneo DOUBLE PRECISION NOT NULL,   -- kVA
    status_energia      BOOLEAN NOT NULL,            -- TRUE = com energia
    horario_leitura     TIMESTAMP NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_leitura_sensor_horario ON leitura_sensor (sensor_id, horario_leitura DESC);

-- ---------- ALERTA (RF03) ----------
CREATE TABLE IF NOT EXISTS alerta (
    id                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transformador_origem_id INTEGER NOT NULL REFERENCES transformador(equipamento_id) ON DELETE CASCADE,
    operador_destinatario_id INTEGER REFERENCES operador(usuario_id) ON DELETE SET NULL,
    mensagem                VARCHAR(255) NOT NULL,
    horario_geracao         TIMESTAMP NOT NULL DEFAULT NOW(),
    tipo_alerta             VARCHAR(20) NOT NULL CHECK (tipo_alerta IN ('TEMPERATURA','CONSUMO')),
    limite_ultrapassado     DOUBLE PRECISION NOT NULL
);

-- ---------- INCIDENTE (RF04) ----------
CREATE TABLE IF NOT EXISTS incidente (
    id                       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transformador_associado_id INTEGER NOT NULL REFERENCES transformador(equipamento_id) ON DELETE RESTRICT,
    operador_atribuido_id    INTEGER REFERENCES operador(usuario_id) ON DELETE SET NULL,
    latitude_ocorrencia      DOUBLE PRECISION NOT NULL,
    longitude_ocorrencia     DOUBLE PRECISION NOT NULL,
    descricao                VARCHAR(255) NOT NULL,
    horario_interrupcao      TIMESTAMP NOT NULL DEFAULT NOW(),
    status_incidente         VARCHAR(20) NOT NULL DEFAULT 'ABERTO'
        CHECK (status_incidente IN ('ABERTO','EM_ATENDIMENTO','RESOLVIDO'))
);

-- ---------- RELATORIO (RF05) ----------
CREATE TABLE IF NOT EXISTS relatorio (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bairro_filtro      VARCHAR(100),
    periodo_inicio     DATE NOT NULL,
    periodo_fim        DATE NOT NULL,
    tipo_relatorio     VARCHAR(40) NOT NULL,
    conteudo_relatorio BYTEA
);
